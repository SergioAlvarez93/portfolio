async function sendRequest(categoriesTree, productsList) {
  if (!OPENROUTER_API_KEY) {
    throw new Error("Не задана переменная окружения OPENROUTER_API_KEY");
  }

  const userContent =
    `Дерево категорий:\n${JSON.stringify(categoriesTree, null, 2)}` +
    `\n\nТовары для категоризации:\n${JSON.stringify(productsList, null, 2)}`;

  const response = await fetch(
    "https://openrouter.ai/api/v1/chat/completions",
    {
      dispatcher: proxy,
      method: "POST",
      headers: {
        Authorization: `Bearer ${OPENROUTER_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "anthropic/claude-opus-5.5",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          { role: "user", content: userContent },
        ],
        response_format: { type: "json_object" },
        reasoning: { effort: "low" },
        max_tokens: 32768,
        usage: { include: true },
      }),
    },
  );

  const data = await response.json();

  if (!response.ok || data.error) {
    throw new Error(
      `OpenRouter API error (${response.status}): ${
        data.error?.message || JSON.stringify(data)
      }`,
    );
  }

  const choice = data.choices?.[0];
  const content = choice?.message?.content;

  console.log(
    `finish_reason: ${choice?.finish_reason}, content length: ${content?.length ?? 0}`,
  );

  if (!content || !content.trim()) {
    throw new Error(`EMPTY_RESPONSE (finish_reason: ${choice?.finish_reason})`);
  }

  return content;
}

async function askAIForCategories(categoriesTree, productsList) {
  if (!OPENROUTER_API_KEY) {
    throw new Error("Не задана переменная окружения OPENROUTER_API_KEY");
  }

  const MAX_RETRIES = 3;
  const RETRY_DELAY_MS = 3000;

  for (let attempt = 1; attempt <= MAX_RETRIES; attempt++) {
    try {
      console.log(`Попытка ${attempt} из ${MAX_RETRIES}...`);

      const content = await sendRequest(categoriesTree, productsList);

      let parsed;

      try {
        parsed = JSON.parse(content);
      } catch {
        console.error("Невалидный JSON от ИИ:");
        console.error(content.slice(0, 500));

        throw new Error("INVALID_JSON");
      }

      if (!Array.isArray(parsed.matches)) {
        throw new Error("INVALID_RESPONSE: отсутствует массив matches");
      }

      console.log("Ответ от ИИ получен.");

      return parsed.matches;
    } catch (err) {
      const retryable =
        err.message === "INVALID_JSON" ||
        err.message.startsWith("EMPTY_RESPONSE") ||
        err.message.includes("429") ||
        err.message.includes("500") ||
        err.message.includes("502") ||
        err.message.includes("503") ||
        err.message.includes("524");

      if (retryable && attempt < MAX_RETRIES) {
        console.warn(`Попытка ${attempt} не удалась: ${err.message}`);
        console.log(`Ждём ${RETRY_DELAY_MS} мс и пробуем снова...`);

        await new Promise((resolve) => setTimeout(resolve, RETRY_DELAY_MS));

        continue;
      }

      throw err;
    }
  }

  throw new Error("Не удалось получить ответ после всех попыток");
}

